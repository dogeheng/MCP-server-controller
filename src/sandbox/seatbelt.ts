import { existsSync, writeFileSync } from 'node:fs';
import { isAbsolute, join, resolve } from 'node:path';
import { expandHome, expandPathTemplate, realpathLoose } from '../util/paths.js';

export const SANDBOX_EXEC = '/usr/bin/sandbox-exec';

export interface SandboxSpec {
  allowWrite: string[]; // templates
  denyRead: string[]; // templates
  network: 'allow' | 'localhost' | 'deny';
  extraRules: string[];
  /** Never writable from inside the sandbox (state dir, config dir), even if under an allowed dir. */
  protectedWrite: string[];
  /** Never readable from inside the sandbox (other sessions' logs, approvals, audit). */
  protectedRead: string[];
}

export interface ResolvedSandbox {
  profile: string;
  writable: string[];
  unreadable: string[];
  network: SandboxSpec['network'];
}

const q = (p: string) => `"${p.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

export function sandboxAvailable(): boolean {
  return existsSync(SANDBOX_EXEC);
}

export function resolveSandbox(spec: SandboxSpec, cwd: string): ResolvedSandbox {
  const uniq = (xs: (string | undefined)[]) => [...new Set(xs.filter((x): x is string => !!x))];
  const writable = uniq(spec.allowWrite.map((p) => expandPathTemplate(p, { cwd })));
  const unreadable = uniq(
    spec.denyRead.flatMap((p) => {
      // Both the resolved and the literal form, in case the path is a symlink.
      const real = expandPathTemplate(p, { cwd });
      const lit = p.includes('{') ? undefined : expandHome(p);
      return [real, lit && isAbsolute(lit) ? resolve(lit) : undefined];
    }),
  );
  const protectedWrite = uniq(spec.protectedWrite.map((p) => realpathLoose(p)));
  const protectedRead = uniq(spec.protectedRead.map((p) => realpathLoose(p)));

  const lines: string[] = [
    '(version 1)',
    ';; Generated by mcp-terminal. Later rules take precedence over earlier ones.',
    '(allow default)',
    '(deny file-write*)',
    '(allow file-write*',
    '  (literal "/dev/null") (literal "/dev/zero") (literal "/dev/tty") (literal "/dev/ptmx")',
    '  (literal "/dev/dtracehelper") (literal "/dev/random") (literal "/dev/urandom")',
    '  (regex #"^/dev/ttys[0-9]+$") (regex #"^/dev/fd/"))',
  ];
  if (writable.length) lines.push(`(allow file-write* ${writable.map((p) => `(subpath ${q(p)})`).join(' ')})`);
  if (protectedWrite.length) lines.push(`(deny file-write* ${protectedWrite.map((p) => `(subpath ${q(p)})`).join(' ')})`);
  const noRead = [...unreadable, ...protectedRead];
  if (noRead.length) lines.push(`(deny file-read* ${noRead.map((p) => `(subpath ${q(p)})`).join(' ')})`);
  // Block the classic escapes from a file sandbox: scripting other apps and
  // asking LaunchServices to open things outside the sandbox.
  lines.push('(deny appleevent-send)');
  lines.push('(deny lsopen)');
  if (spec.network === 'localhost') {
    lines.push('(deny network-outbound (remote ip "*:*"))');
    lines.push('(allow network-outbound (remote ip "localhost:*"))');
  } else if (spec.network === 'deny') {
    lines.push('(deny network-outbound (remote ip "*:*"))');
  }
  lines.push(...spec.extraRules);
  return { profile: `${lines.join('\n')}\n`, writable, unreadable: noRead, network: spec.network };
}

export function writeProfile(runDir: string, profile: string): string {
  const p = join(runDir, 'sandbox.sb');
  writeFileSync(p, profile, { mode: 0o600 });
  return p;
}

export function wrapArgv(profilePath: string, argv: string[]): string[] {
  return [SANDBOX_EXEC, '-f', profilePath, ...argv];
}
