import { writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { ensureDir } from '../util/paths.js';

export type ShellKind = 'zsh' | 'bash' | 'other';

export interface ShellPrepOptions {
  shell: string;
  nonce: string;
  runDir: string;
  rc: 'user' | 'clean';
  history: 'off' | 'user';
  login: boolean;
  scrubPatterns: string[];
  /** ZDOTDIR of the server's environment, if any. */
  userZdotdir?: string;
}

export interface ShellPrep {
  argv: string[];
  env: Record<string, string>;
  kind: ShellKind;
  integration: boolean;
}

export const KEEP_VARS = ['MCP_TERMINAL', 'MCP_TERMINAL_SESSION_ID', 'PATH', 'HOME', 'USER', 'SHELL', 'TERM'];

export function shellKind(shell: string): ShellKind {
  const b = basename(shell);
  if (b === 'zsh' || b.startsWith('zsh-')) return 'zsh';
  if (b === 'bash' || b.startsWith('bash-')) return 'bash';
  return 'other';
}

/** Only plain glob characters are allowed into generated shell code. */
export function safeGlobs(patterns: string[]): string[] {
  return patterns.filter((p) => /^[A-Za-z0-9_*?]+$/.test(p));
}

const sq = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

function zshSourceUser(file: string, rc: string): string {
  return `if [[ ${sq(rc)} == user && -f "$__mcpt_zd/${file}" ]]; then
  ZDOTDIR="$__mcpt_zd"
  builtin source "$__mcpt_zd/${file}"
  __mcpt_zd="$ZDOTDIR"
  ZDOTDIR="$__mcpt_self_zd"
fi
`;
}

function zshRestoreZdotdir(userZdotdir: string): string {
  return `if [[ -z ${sq(userZdotdir)} && "$__mcpt_zd" == "$HOME" ]]; then
  builtin unset ZDOTDIR
else
  ZDOTDIR="$__mcpt_zd"
fi
`;
}

export function prepareShell(o: ShellPrepOptions): ShellPrep {
  const kind = shellKind(o.shell);
  const scrub = safeGlobs(o.scrubPatterns).join('|');
  const keep = KEEP_VARS.join('|');
  if (kind === 'zsh') {
    const zd = ensureDir(join(o.runDir, 'zdotdir'));
    const user = o.userZdotdir ?? '';
    const header = '# Generated by mcp-terminal for one session. Do not edit.\n';
    writeFileSync(
      join(zd, '.zshenv'),
      `${header}typeset -g __mcpt_self_zd="$ZDOTDIR"
typeset -g __mcpt_zd=${sq(user)}
[[ -z "$__mcpt_zd" ]] && __mcpt_zd="$HOME"
${zshSourceUser('.zshenv', o.rc)}`,
      { mode: 0o600 },
    );
    writeFileSync(join(zd, '.zprofile'), `${header}${zshSourceUser('.zprofile', o.rc)}`, { mode: 0o600 });
    writeFileSync(
      join(zd, '.zshrc'),
      `${header}${zshSourceUser('.zshrc', o.rc)}
if [[ ${sq(o.history)} == off ]]; then
  builtin unset HISTFILE
  SAVEHIST=0
fi
if [[ -n ${sq(scrub)} ]]; then
  for __mcpt_v in \${(k)parameters}; do
    [[ \${parameters[$__mcpt_v]} == *export* ]] || continue
    case $__mcpt_v in
      (${keep}) ;;
      (${scrub || '__mcpt_never__'}) builtin unset $__mcpt_v ;;
    esac
  done
  builtin unset __mcpt_v
fi
typeset -g __mcpt_n=${sq(o.nonce)}
__mcpt_precmd() {
  local __mcpt_ec=$?
  builtin printf '\\e]133;D;%s;n=%s\\a\\e]7;file://%s%s\\a\\e]133;A;n=%s\\a' "$__mcpt_ec" "$__mcpt_n" "$HOST" "$PWD" "$__mcpt_n"
  if [[ "\${precmd_functions[1]}" != __mcpt_precmd ]]; then
    precmd_functions=(__mcpt_precmd \${precmd_functions:#__mcpt_precmd})
  fi
  return $__mcpt_ec
}
__mcpt_preexec() {
  builtin printf '\\e]133;C;n=%s\\a' "$__mcpt_n"
}
typeset -ga precmd_functions preexec_functions
precmd_functions=(__mcpt_precmd \${precmd_functions:#__mcpt_precmd})
preexec_functions=(\${preexec_functions:#__mcpt_preexec} __mcpt_preexec)
if [[ ! -o login ]]; then
${zshRestoreZdotdir(user)}fi
`,
      { mode: 0o600 },
    );
    writeFileSync(
      join(zd, '.zlogin'),
      `${header}${zshSourceUser('.zlogin', o.rc)}${zshRestoreZdotdir(user)}`,
      { mode: 0o600 },
    );
    const argv = [o.shell];
    if (o.login) argv.push('-l');
    argv.push('-i');
    return { argv, env: { ZDOTDIR: zd }, kind, integration: true };
  }
  if (kind === 'bash') {
    const rcfile = join(ensureDir(o.runDir), 'bashrc');
    writeFileSync(
      rcfile,
      `# Generated by mcp-terminal for one session. Do not edit.
if [[ ${sq(o.rc)} == user ]]; then
  if [[ ${sq(o.login ? '1' : '0')} == 1 ]]; then
    [[ -f /etc/profile ]] && . /etc/profile
    if [[ -f ~/.bash_profile ]]; then . ~/.bash_profile
    elif [[ -f ~/.bash_login ]]; then . ~/.bash_login
    elif [[ -f ~/.profile ]]; then . ~/.profile
    fi
  else
    [[ -f ~/.bashrc ]] && . ~/.bashrc
  fi
fi
if [[ ${sq(o.history)} == off ]]; then
  unset HISTFILE
fi
if [[ -n ${sq(scrub)} ]]; then
  for __mcpt_v in $(compgen -e); do
    case "$__mcpt_v" in
      ${keep}) ;;
      ${scrub || '__mcpt_never__'}) unset "$__mcpt_v" ;;
    esac
  done
  unset __mcpt_v
fi
__mcpt_n=${sq(o.nonce)}
__mcpt_precmd() {
  local __mcpt_ec=$?
  builtin printf '\\033]133;D;%s;n=%s\\007\\033]7;file://%s%s\\007\\033]133;A;n=%s\\007' "$__mcpt_ec" "$__mcpt_n" "$HOSTNAME" "$PWD" "$__mcpt_n"
  return $__mcpt_ec
}
if [[ -z "$PROMPT_COMMAND" ]]; then
  PROMPT_COMMAND=__mcpt_precmd
else
  PROMPT_COMMAND="__mcpt_precmd;$PROMPT_COMMAND"
fi
if (( BASH_VERSINFO[0] > 4 || (BASH_VERSINFO[0] == 4 && BASH_VERSINFO[1] >= 4) )); then
  PS0=$'\\e]133;C;n='"$__mcpt_n"$'\\a'
fi
`,
      { mode: 0o600 },
    );
    return {
      argv: [o.shell, '--rcfile', rcfile, '-i'],
      env: { BASH_SILENCE_DEPRECATION_WARNING: '1' },
      kind,
      integration: true,
    };
  }
  const argv = [o.shell];
  if (o.login) argv.push('-l');
  argv.push('-i');
  return { argv, env: {}, kind, integration: false };
}

/** Sentinel appended to a command when the shell has no integration (degraded mode). */
export function sentinelSuffix(nonce: string): string {
  return ` ; printf '\\033]133;D;%s;n=${nonce}\\007' "$?"`;
}
